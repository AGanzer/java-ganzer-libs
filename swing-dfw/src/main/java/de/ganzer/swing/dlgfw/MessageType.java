package de.ganzer.swing.dlgfw;

/**
 * The type of the default title and default icon to display within a
 * {@link MessageDialog}.
 *
 * @since 6.3.0
 */
public enum MessageType {
    /**
     * An information message.
     */
    INFORMATION,
    /**
     * A warning message.
     */
    WARNING,
    /**
     * An error message.
     */
    ERROR,
    /**
     * A question message.
     */
    QUESTION
}
